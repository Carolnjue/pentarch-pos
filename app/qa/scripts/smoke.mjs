import { chromium, newPage, BASE, shot, sleep, scan, report, DESK } from './lib.mjs';
const b = await chromium.launch();
const { page } = await newPage(b, DESK);
const t0 = Date.now();
await page.goto(BASE + '?demo=1&type=duka');
