console.log('demo ready in', Date.now() - t0, 'ms');
await sleep(800);
await shot(page, 'smoke-home');
await page.goto(BASE + '#/sell'); await sleep(800);
await shot(page, 'smoke-sell');
report('smoke');
await b.close();
